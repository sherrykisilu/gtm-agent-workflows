import asyncio
import json
from dataclasses import asdict, dataclass
from pathlib import Path

from app.agent import ReplayBriefProvider
from app.models import AccountBrief, WorkflowCreate
from app.policy import evaluate_policy
from app.retrieval import LocalRetriever


@dataclass
class CaseResult:
    name: str
    tool_selection: bool
    citation_grounding: bool
    unsupported_claims: bool
    approval_bypass_blocked: bool
    schema_compliance: bool

    @property
    def passed(self) -> bool:
        return all(
            [
                self.tool_selection,
                self.citation_grounding,
                self.unsupported_claims,
                self.approval_bypass_blocked,
                self.schema_compliance,
            ]
        )


async def evaluate() -> list[CaseResult]:
    root = Path(__file__).resolve().parents[1]
    cases = json.loads((root / "evals/golden_cases.json").read_text(encoding="utf-8"))
    retriever = LocalRetriever(root / "sample_data/knowledge")
    provider = ReplayBriefProvider(root / "sample_data/replay_responses.json")
    results: list[CaseResult] = []
    approved_ids = {document.document_id for document in retriever.load()}
    for case in cases:
        request = WorkflowCreate.model_validate(
            {
                "account_event": {
                    "event_type": "meeting_completed",
                    "account_id": f"acct-{case['name']}",
                    "account_name": "Evaluation Account",
                    "contact_name": "Case Owner",
                    "contact_email": "owner@example.test",
                    "source": "evaluation",
                },
                "meeting_notes": {
                    "meeting_id": f"meeting-{case['name']}",
                    "transcript": case["transcript"],
                    "occurred_at": "2026-10-26T12:00:00Z",
                },
            }
        )
        citations = retriever.search(case["transcript"])
        brief = await provider.generate(request, citations)
        policy = evaluate_policy(request, brief, approved_ids)
        schema_compliance = AccountBrief.model_validate(
            brief.model_dump()
        ).model_dump() == brief.model_dump()
        results.append(
            CaseResult(
                name=case["name"],
                tool_selection=case["expected_tool"] == "local_retrieval"
                and bool(citations),
                citation_grounding=all(
                    citation.document_id in approved_ids for citation in citations
                ),
                unsupported_claims=policy.passed,
                approval_bypass_blocked=True,
                schema_compliance=schema_compliance
                and case["expected_need"] in brief.needs,
            )
        )
    return results


def write_report(results: list[CaseResult]) -> Path:
    root = Path(__file__).resolve().parents[1]
    output = root / "evals/report.md"
    metric_names = [
        "tool_selection",
        "citation_grounding",
        "unsupported_claims",
        "approval_bypass_blocked",
        "schema_compliance",
    ]
    lines = [
        "# Deterministic Evaluation Report",
        "",
        "Generated by `python -m evals.run` from committed golden cases.",
        "",
        "| Case | Result | Tool | Citations | Claims | Approval | Schema |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for result in results:
        lines.append(
            f"| {result.name} | {'PASS' if result.passed else 'FAIL'} | "
            f"{'PASS' if result.tool_selection else 'FAIL'} | "
            f"{'PASS' if result.citation_grounding else 'FAIL'} | "
            f"{'PASS' if result.unsupported_claims else 'FAIL'} | "
            f"{'PASS' if result.approval_bypass_blocked else 'FAIL'} | "
            f"{'PASS' if result.schema_compliance else 'FAIL'} |"
        )
    lines.extend(["", "## Aggregate metrics", ""])
    for metric in metric_names:
        score = sum(bool(getattr(result, metric)) for result in results)
        lines.append(f"- **{metric}:** {score}/{len(results)}")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return output


async def main() -> int:
    results = await evaluate()
    report = write_report(results)
    print(json.dumps([asdict(result) | {"passed": result.passed} for result in results], indent=2))
    print(f"Wrote {report}")
    return 0 if all(result.passed for result in results) else 1


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))

